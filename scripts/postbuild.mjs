// After `next build`, write out/sw.js with a precache list of every exported file, so the
// whole app (all lessons included) works offline after the first visit.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../out/", import.meta.url));
const base = process.env.NEXT_PUBLIC_BASE_PATH || "";
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : files.push(relative(out, p).split(sep).join("/")); } };
walk(out);
const urls = files.filter((f) => !f.endsWith(".txt") && f !== "sw.js" && !f.endsWith(".map"))
  .map((f) => `${base}/${f.replace(/index\.html$/, "")}`);
const version = Date.now().toString(36);
writeFileSync(join(out, "sw.js"), `// generated by scripts/postbuild.mjs
const V = "ft-${version}", FONTS = "ft-fonts";
const PRE = ${JSON.stringify(urls)};
self.addEventListener("install", (e) => e.waitUntil(caches.open(V).then((c) => c.addAll(PRE)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== V && k !== FONTS).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", (e) => {
  const u = new URL(e.request.url);
  if (e.request.method !== "GET") return;
  if (u.hostname === "api.github.com") return; // sync always goes to the network
  if (u.hostname.endsWith("fonts.googleapis.com") || u.hostname.endsWith("fonts.gstatic.com")) {
    e.respondWith(caches.open(FONTS).then(async (c) => (await c.match(e.request)) || fetch(e.request).then((r) => { c.put(e.request, r.clone()); return r; })));
    return;
  }
  if (u.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: e.request.mode === "navigate" }).then((hit) => hit || fetch(e.request).then((r) => {
    if (r.ok) { const copy = r.clone(); caches.open(V).then((c) => c.put(e.request, copy)); }
    return r;
  }).catch(() => caches.match("${base}/"))));
});
`);
console.log(`sw.js: precached ${urls.length} files`);
